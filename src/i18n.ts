const dictionaries: Record<Language, Record<MessageKey, string>> = { en, es };

/** "1 franchise" / "3 franchises" without pretending English plurals are universal. */
export function qty(t: TFn, n: number, singular: MessageKey, plural: MessageKey): string {
  return `${n} ${t(n === 1 ? singular : plural)}`;
}

export function translate(language: Language, key: MessageKey, values?: Record<string, string | number>): string {
  let message: string = dictionaries[language][key] ?? dictionaries.en[key];
  if (values) {
    for (const [name, value] of Object.entries(values)) message = message.replaceAll(`{${name}}`, String(value));
  }
  return message;
}
